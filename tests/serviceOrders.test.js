import assert from 'node:assert/strict';
import { emptyOrders, createOrder, transitionOrder, wallet, redeemReward, addOrderMessage, validateOrders } from '../src/Utils/serviceOrders.js';
const service = id => ({ id, kind: 'request', t: 'Revisão', loc: 'Centro', by: 'Cliente', ownerId: 'client' });
const photo = 'data:image/jpeg;base64,/9j/2Q==';
let data = createOrder(emptyOrders(), service(1), 'Oficina');
assert.equal(createOrder(data, service(1), 'Oficina'), data);
assert.throws(() => transitionOrder(data, 'order:1', 'completed', {photo}));
assert.throws(() => transitionOrder(data, 'order:1', 'cancelled', {reason:'Motivo suficiente'}));
data = transitionOrder(data, 'order:1', 'accepted');
assert.throws(() => transitionOrder(data, 'order:1', 'cancelled', {reason:'Curto'}));
assert.throws(() => transitionOrder(data, 'order:1', 'completed'));
assert.equal(wallet(data).balance, 0);
data = transitionOrder(data, 'order:1', 'completed', {photo});
assert.equal(wallet(data).balance, 100);
assert.throws(() => transitionOrder(data, 'order:1', 'completed', {photo}));
assert.throws(() => transitionOrder(data, 'order:1', 'cancelled', {reason:'Não pode cancelar concluído'}));
assert.throws(() => redeemReward(data, 'mobility'));
data = createOrder(data, service(2), 'Oficina');
data = transitionOrder(data, 'order:2', 'accepted');
data = transitionOrder(data, 'order:2', 'cancelled', {reason:'Peça indisponível no fornecedor'});
assert.equal(wallet(data).balance, 100);
assert.equal(data.orders[0].reason, 'Peça indisponível no fornecedor');
data = createOrder(data, service(3), 'Oficina');
data = transitionOrder(data, 'order:3', 'refused');
assert.throws(() => transitionOrder(data, 'order:3', 'accepted'));
data = createOrder(data, service(4), 'Oficina');
data = transitionOrder(data, 'order:4', 'accepted');
data = transitionOrder(data, 'order:4', 'completed', {photo});
assert.equal(wallet(data).balance, 200);
data = redeemReward(data, 'mobility');
assert.equal(wallet(data).balance, 0);
assert.equal(data.redemptions.length, 1);
assert.throws(() => redeemReward(data, 'mobility'));
data = addOrderMessage(data, 'order:1', 'client', 'Obrigado!');
assert.equal(data.orders.find(o => o.id === 'order:1').messages[0].sender, 'client');
assert.deepEqual(validateOrders(JSON.parse(JSON.stringify(data))), data);
assert.throws(() => validateOrders({...data,orders:[{...data.orders.find(o=>o.status==='completed'),photo:''}]}));
console.log('OK: transições, motivo obrigatório, foto obrigatória, pontos únicos, saldo e persistência JSON.');
